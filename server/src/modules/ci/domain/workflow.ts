import {
  ACTION_PINS,
  ALLOWED_TRIGGERS,
  CI_BRANCH,
  FORK_GUARD_EXPR,
  NODE_VERSION,
  POST_AS_VALUES,
  RESULT_FILE_NAME,
  RUNNER_OS,
  RUNNER_RUN_COMMAND,
  SLUG_PATTERN,
  artifactNameFor,
  checkNameFor,
  type CiPostAs,
  type CiTrigger,
} from './constants.js';

/**
 * Validate the requested triggers (FR15): a non-empty list made only of known
 * `pull_request` types. Returns them de-duplicated in canonical order, or null.
 */
export function normalizeTriggers(triggers: readonly string[]): CiTrigger[] | null {
  if (triggers.length === 0) return null;
  const requested = new Set(triggers);
  if (![...requested].every((t) => (ALLOWED_TRIGGERS as readonly string[]).includes(t))) {
    return null;
  }
  return ALLOWED_TRIGGERS.filter((t) => requested.has(t));
}

export interface WorkflowOptions {
  slug: string;
  triggers: readonly CiTrigger[];
  postAs: CiPostAs;
}

/**
 * The hardened per-agent GitHub Actions workflow (FR9). Every line is security
 * relevant: it must pass `checkWorkflow` (application/workflow-check.ts). Interpolated
 * values are validated first so nothing user-controlled reaches the YAML text.
 * `${{` is escaped in the template literals below.
 */
export function buildWorkflow({ slug, triggers, postAs }: WorkflowOptions): string {
  if (!SLUG_PATTERN.test(slug)) throw new Error('invalid slug');
  if (triggers.length === 0 || !triggers.every((t) => ALLOWED_TRIGGERS.includes(t))) {
    throw new Error('invalid triggers');
  }
  if (!POST_AS_VALUES.includes(postAs)) throw new Error('invalid post_as');
  const check = checkNameFor(slug);

  return `name: ${check}

on:
  pull_request:
    types: [${triggers.join(', ')}]

permissions:
  contents: read
  pull-requests: write

jobs:
  review:
    name: ${check}
    if: ${FORK_GUARD_EXPR}
    runs-on: ${RUNNER_OS}
    steps:
      - name: Check out the pull request
        uses: ${ACTION_PINS.checkout}
        with:
          ref: \${{ github.event.pull_request.head.sha }}
          persist-credentials: false

      - name: Set up Node.js
        uses: ${ACTION_PINS.setupNode}
        with:
          node-version: '${NODE_VERSION}'

      - name: Run the DevDigest review
        run: ${RUNNER_RUN_COMMAND}
        env:
          OPENROUTER_API_KEY: \${{ secrets.OPENROUTER_API_KEY }}
          GITHUB_TOKEN: \${{ secrets.GITHUB_TOKEN }}
          DEVDIGEST_AGENT: ${slug}
          DEVDIGEST_POST_AS: ${postAs}
          PR_HEAD_SHA: \${{ github.event.pull_request.head.sha }}

      - name: Upload the review result
        if: always()
        uses: ${ACTION_PINS.uploadArtifact}
        with:
          name: ${artifactNameFor(slug)}
          path: ${RESULT_FILE_NAME}
`;
}

/** Body of the export PR (EC17): files, the secret to add (name only), the check name. */
export function buildPrBody({ slug, paths }: { slug: string; paths: readonly string[] }): string {
  const files = paths.map((p) => `- \`${p}\``).join('\n');
  return [
    `Adds the DevDigest review agent \`${slug}\` to this repository's GitHub Actions.`,
    '',
    '### Files',
    files,
    '',
    '### Before merging',
    '1. Add the repository Actions secret `OPENROUTER_API_KEY` (Settings > Secrets and variables > Actions).',
    '   This PR triggers the review workflow on itself, so its check stays red until the secret exists.',
    '2. Merge this PR.',
    `3. To block merges on CRITICAL findings, add the status check \`${checkNameFor(slug)}\` as required in the branch protection of the default branch.`,
    '',
    `Branch: \`${CI_BRANCH}\`. Generated by DevDigest.`,
  ].join('\n');
}
